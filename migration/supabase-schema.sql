-- Joblink cloud schema. Run on a NEW Supabase project only.
-- Existing login accounts remain application users; this does not use auth.users.
begin;
create table if not exists public.users (
 id bigint generated by default as identity primary key,
 name varchar(100) not null,
 email varchar(254) not null,
 password_hash varchar(255),
 google_sub varchar(255) unique,
 email_verified boolean not null default false,
 avatar_url varchar(2048),
 created_at timestamptz not null default now()
);
create unique index if not exists joblink_email_unique on public.users(lower(email));
create table if not exists public.workspace_items (
 id bigint generated by default as identity primary key,
 user_id bigint not null references public.users(id) on delete cascade,
 kind varchar(32) not null check(kind in ('application','task','task_status','event','link','sheet')),
 payload jsonb not null check(jsonb_typeof(payload)='object'),
 created_at timestamptz not null default now()
);
create index if not exists joblink_workspace_owner on public.workspace_items(user_id,kind);
create table if not exists public.workspace_attachments (
 id bigint generated by default as identity primary key,
 user_id bigint not null references public.users(id) on delete cascade,
 item_id bigint not null references public.workspace_items(id) on delete cascade,
 name varchar(200) not null,
 stored_name char(32) not null check(stored_name ~ '^[a-f0-9]{32}$'),
 mime varchar(150) not null,
 size integer not null check(size between 1 and 2097152),
 storage_path text not null unique
);
create index if not exists joblink_attachment_owner on public.workspace_attachments(user_id,item_id);
create table if not exists public.auth_attempts (
 attempt_key char(64) not null,
 window_id bigint not null,
 attempts integer not null,
 primary key(attempt_key,window_id)
);
create table if not exists public.joblink_sessions (
 token_hash char(64) primary key,
 user_id bigint not null references public.users(id) on delete cascade,
 csrf_token char(64) not null,
 expires_at timestamptz not null,
 created_at timestamptz not null default now()
);
create index if not exists joblink_session_expiry on public.joblink_sessions(expires_at);
-- Browser keys must not read these tables, particularly password hashes.
-- Cloud Node routes authorize each user, then use a server-only Supabase secret key.
alter table public.users enable row level security;
alter table public.workspace_items enable row level security;
alter table public.workspace_attachments enable row level security;
alter table public.auth_attempts enable row level security;
alter table public.joblink_sessions enable row level security;
revoke all on public.users,public.workspace_items,public.workspace_attachments,public.auth_attempts,public.joblink_sessions from anon,authenticated;
grant all on public.users,public.workspace_items,public.workspace_attachments,public.auth_attempts,public.joblink_sessions to service_role;
grant usage,select on all sequences in schema public to service_role;
-- Advance generated IDs after preserving local IDs during import.
create or replace function public.joblink_finalize_import() returns void
language plpgsql security definer set search_path=public as $$
begin
 perform setval(pg_get_serial_sequence('public.users','id'),coalesce((select max(id) from public.users),1),(select count(*)>0 from public.users));
 perform setval(pg_get_serial_sequence('public.workspace_items','id'),coalesce((select max(id) from public.workspace_items),1),(select count(*)>0 from public.workspace_items));
 perform setval(pg_get_serial_sequence('public.workspace_attachments','id'),coalesce((select max(id) from public.workspace_attachments),1),(select count(*)>0 from public.workspace_attachments));
end;
$$;
revoke all on function public.joblink_finalize_import() from public,anon,authenticated;
grant execute on function public.joblink_finalize_import() to service_role;
commit;
-- Atomic data import: refuses to overwrite an existing cloud database.
create or replace function public.joblink_import_snapshot(snapshot jsonb) returns jsonb
language plpgsql security definer set search_path=public as $$
declare table_data jsonb;
begin
 perform pg_advisory_xact_lock(810102026);
 if exists(select 1 from public.users) or exists(select 1 from public.workspace_items) or exists(select 1 from public.workspace_attachments) then
  raise exception 'Target tables are not empty. Import refused to protect cloud records.';
 end if;
 if snapshot->>'version' is distinct from '1' then raise exception 'Unsupported snapshot version'; end if;
 table_data := snapshot->'tables';
 if jsonb_typeof(table_data->'users') is distinct from 'array' or jsonb_typeof(table_data->'workspace_items') is distinct from 'array' or jsonb_typeof(table_data->'workspace_attachments') is distinct from 'array' then raise exception 'Invalid snapshot tables'; end if;
 insert into public.users(id,name,email,password_hash,google_sub,email_verified,avatar_url,created_at)
 select id,name,email,password_hash,google_sub,email_verified,avatar_url,created_at
 from jsonb_to_recordset(table_data->'users') as x(id bigint,name text,email text,password_hash text,google_sub text,email_verified boolean,avatar_url text,created_at timestamptz);
 insert into public.workspace_items(id,user_id,kind,payload,created_at)
 select id,user_id,kind,payload,created_at
 from jsonb_to_recordset(table_data->'workspace_items') as x(id bigint,user_id bigint,kind text,payload jsonb,created_at timestamptz);
 insert into public.workspace_attachments(id,user_id,item_id,name,stored_name,mime,size,storage_path)
 select x.id,x.user_id,x.item_id,x.name,x.stored_name,x.mime,x.size,x.storage_path
 from jsonb_to_recordset(table_data->'workspace_attachments') as x(id bigint,user_id bigint,item_id bigint,name text,stored_name text,mime text,size integer,storage_path text)
 join public.workspace_items i on i.id=x.item_id and i.user_id=x.user_id;
 if (select count(*) from public.workspace_attachments) <> jsonb_array_length(table_data->'workspace_attachments') then raise exception 'Attachment ownership mismatch'; end if;
 perform public.joblink_finalize_import();
 return jsonb_build_object('users',(select count(*) from public.users),'workspace_items',(select count(*) from public.workspace_items),'workspace_attachments',(select count(*) from public.workspace_attachments));
end;
$$;
revoke all on function public.joblink_import_snapshot(jsonb) from public,anon,authenticated;
grant execute on function public.joblink_import_snapshot(jsonb) to service_role;
